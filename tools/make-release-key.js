#!/usr/bin/env node
/* ============================================================
   FieldKit :: tools/make-release-key.js

   Makes the keypair that signs releases (§14.4).

   WHY A SIGNATURE AND NOT A CHECKSUM

   Auto-update is a remote-code path into the application that
   holds the vault. Whoever can decide what FieldKit downloads next
   can hand you a modified core/crypto.js, and the version that
   reads your passphrase looks exactly like the version that does
   not. A SHA-256 published beside the file proves nothing: anyone
   who can replace the file can replace the hash next to it.

   A signature moves the trust from the server to a key. The relay
   can be taken over completely and still cannot produce a release
   FieldKit will accept, because the private half is not there — it
   is on the SSD, in a gitignored file, and it never travels.

   ---- WHY ECDSA P-256 ------------------------------------------

   Ed25519 is the nicer algorithm and browser support for it is
   still uneven. P-256 with SHA-256 is in every engine that has
   crypto.subtle at all, which is the same bar the rest of FieldKit
   is built to. Signatures are written in IEEE P1363 form (raw
   r||s) rather than Node's default DER, because that is what
   WebCrypto's verify() expects and converting in the browser would
   be code that only exists to undo a choice made here.

   USAGE

     node tools/make-release-key.js

   Writes two files:

     release-key.json   the PRIVATE key. Gitignored. Never leaves
                        the SSD. Losing it means future releases
                        cannot be signed; LEAKING it means someone
                        else can sign one, which is worse.

     core/update-key.js the PUBLIC key, as a classic script that
                        assigns a global. Committed, and it ships in
                        the build so the running app carries its own
                        verifier.

   It refuses to overwrite an existing private key. Rotating on
   purpose means deleting it by hand first, and then every older
   release stops verifying — which is the point of rotating.
   ============================================================ */
"use strict";

const crypto = require("crypto");
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const PRIVATE = path.join(ROOT, "release-key.json");
const PUBLIC = path.join(ROOT, "core", "update-key.js");

function die(msg) { process.stderr.write("\n" + msg + "\n"); process.exit(1); }

if (fs.existsSync(PRIVATE)) {
  die("release-key.json already exists.\n\n" +
    "Refusing to overwrite it. If you genuinely mean to rotate the key,\n" +
    "delete that file first — and be aware that every release signed with\n" +
    "the old one stops verifying the moment the new public key ships.");
}

const { publicKey, privateKey } = crypto.generateKeyPairSync("ec", { namedCurve: "prime256v1" });

const spki = publicKey.export({ type: "spki", format: "der" }).toString("base64");
const pkcs8 = privateKey.export({ type: "pkcs8", format: "der" }).toString("base64");

/* A fingerprint of the public key, printed here and shown by the
   updater. Two people comparing four groups of hex out loud is the
   only check that does not go through the relay — and the relay is
   the thing the signature exists to distrust. */
const fingerprint = crypto.createHash("sha256").update(Buffer.from(spki, "base64"))
  .digest("hex").slice(0, 16).toUpperCase().replace(/(.{4})/g, "$1 ").trim();

fs.writeFileSync(PRIVATE, JSON.stringify({
  algorithm: "ECDSA-P256-SHA256",
  created: new Date().toISOString(),
  fingerprint: fingerprint,
  privateKeyPkcs8B64: pkcs8,
  publicKeySpkiB64: spki,
  _warning: "PRIVATE. This signs releases. Anyone holding it can hand FieldKit " +
    "a modified build that verifies. It is gitignored; keep it that way, and keep " +
    "a copy somewhere that is not this drive."
}, null, 2), "utf8");

fs.writeFileSync(PUBLIC,
`/* ============================================================
   FieldKit :: update-key
   The PUBLIC half of the release signing key (§14.4).

   Generated by tools/make-release-key.js. Committed on purpose:
   this is what makes the running app able to check a release for
   itself, without asking the relay whether the relay is honest.

   Changing this file changes what FieldKit will accept as an
   update. It should move only when the key is rotated deliberately,
   and a diff touching it deserves a second look.

   Fingerprint: ${fingerprint}
   Generated:   ${new Date().toISOString()}
   ============================================================ */
(function (FieldKit) {
  "use strict";

  FieldKit.provide("updateKey", {
    algorithm: "ECDSA-P256-SHA256",
    /* SPKI DER, base64. crypto.subtle.importKey("spki", ...) takes
       this directly. */
    spki: ${JSON.stringify(spki)},
    /* Shown by the updater so it can be read aloud and compared
       against the value printed when the key was made. The relay
       never sees this and cannot influence it. */
    fingerprint: ${JSON.stringify(fingerprint)}
  });
})(window.FieldKit);
`, "utf8");

process.stdout.write([
  "",
  "FieldKit :: release signing key created",
  "",
  "  private  release-key.json      (gitignored — never upload this)",
  "  public   core/update-key.js    (committed — ships in the build)",
  "",
  "  fingerprint  " + fingerprint,
  "",
  "Write that fingerprint down somewhere that is not this drive. The",
  "updater shows it, and comparing the two is the one check that does",
  "not go through the relay.",
  "",
  "Next:  node build.js --release",
  ""
].join("\n"));
